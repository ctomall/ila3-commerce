#!/usr/bin/env node
/**
 * Route manifest generator (T4).
 *
 * Sources (read-only):
 *   - .mercato/generated/modules.generated.ts  (`pattern: "..."` entries)
 *   - route.ts handlers anywhere under src/app
 *
 * Output:
 *   - docs/routes.md
 *
 * The script is idempotent: the same inputs produce byte-identical output (no
 * timestamps or absolute paths are written), and it never writes into .mercato.
 *
 * Count guard: the number of backend `pattern:` entries extracted from the
 * registry must equal the number of backend rows written to docs/routes.md.
 * Any drift exits 1 so a regeneration cannot silently drop routes.
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const MODULES_FILE = path.join(root, '.mercato', 'generated', 'modules.generated.ts')
const APP_DIR = path.join(root, 'src', 'app')
const OUTPUT_FILE = path.join(root, 'docs', 'routes.md')

const PATTERN_RE = /pattern:\s*"([^"]+)"/g
const ROUTE_GROUP_RE = /^\(.*\)$/
const BACKEND_HEADING = 'Backend 页面路由'
const API_HEADING = 'API 路由'
const OTHER_HEADING = '其它路由'

function fail(message) {
  console.error(`[routes] FAIL: ${message}`)
  process.exit(1)
}

function readModulePatterns() {
  let source
  try {
    source = fs.readFileSync(MODULES_FILE, 'utf8')
  } catch (error) {
    fail(`cannot read ${path.relative(root, MODULES_FILE)}: ${error instanceof Error ? error.message : String(error)}`)
  }
  return [...source.matchAll(PATTERN_RE)].map((match) => match[1])
}

function walk(dir, files = []) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name)
    if (entry.isDirectory()) walk(full, files)
    else if (entry.isFile()) files.push(full)
  }
  return files
}

function readAppRouteHandlers() {
  if (!fs.existsSync(APP_DIR)) return []
  return walk(APP_DIR)
    .filter((full) => path.basename(full) === 'route.ts')
    .map((full) => {
      const relative = path
        .relative(APP_DIR, full)
        .split(path.sep)
        .join('/')
        .replace(/(?:^|\/)route\.ts$/, '')
      // Route groups such as (backend) are organisational only and never appear
      // in the public URL.
      const segments = relative
        .split('/')
        .filter((segment) => segment.length > 0 && !ROUTE_GROUP_RE.test(segment))
      return segments.length > 0 ? `/${segments.join('/')}` : '/'
    })
    .sort()
}

function buildSections() {
  const modulePatterns = readModulePatterns()
  const routeHandlers = readAppRouteHandlers()
  const backend = []
  const api = []
  const other = []

  for (const pattern of modulePatterns) {
    if (pattern === '/backend' || pattern.startsWith('/backend/')) backend.push(pattern)
    else if (pattern === '/api' || pattern.startsWith('/api/')) api.push(pattern)
    else other.push(pattern)
  }
  for (const handler of routeHandlers) {
    if (handler === '/api' || handler.startsWith('/api/')) api.push(handler)
    else other.push(handler)
  }

  // Deterministic order; every extracted entry is preserved so the count guard
  // below is a literal one-to-one check.
  backend.sort()
  api.sort()
  other.sort()
  return { modulePatterns, routeHandlers, backend, api, other }
}

function renderManifest(sections) {
  const total = sections.backend.length + sections.api.length + sections.other.length
  const table = (rows) => ['| Route |', '| --- |', ...rows.map((route) => `| \`${route}\` |`)]
  return [
    '# Route manifest',
    '',
    '> Generated by `node scripts/generate-routes-manifest.mjs`; do not edit by hand.',
    '> Sources: `pattern: "..."` entries in `.mercato/generated/modules.generated.ts` and `src/app/**/route.ts`.',
    '',
    `Registry patterns extracted: ${sections.modulePatterns.length}`,
    `Backend page patterns extracted: ${sections.backend.length}`,
    '',
    `## ${BACKEND_HEADING} (${sections.backend.length})`,
    '',
    ...table(sections.backend),
    '',
    `## ${API_HEADING} (${sections.api.length})`,
    '',
    ...table(sections.api),
    '',
    `## ${OTHER_HEADING} (${sections.other.length})`,
    '',
    ...table(sections.other),
    '',
    `Total: ${total} routes (${sections.backend.length} backend page + ${sections.api.length} API + ${sections.other.length} other).`,
    '',
  ].join('\n')
}

function sectionRows(markdown, headingPrefix) {
  const sections = markdown.split(/\n## /).slice(1)
  const section = sections.find((part) => part.startsWith(headingPrefix))
  if (!section) return -1
  return section.split('\n').filter((line) => line.startsWith('| `')).length
}

function headingCount(markdown, headingPrefix) {
  const line = markdown.split('\n').find((candidate) => candidate.startsWith(`## ${headingPrefix}`))
  const match = line?.match(/\((\d+)\)\s*$/)
  return match ? Number(match[1]) : Number.NaN
}

const sections = buildSections()
const total = sections.backend.length + sections.api.length + sections.other.length
const manifest = renderManifest(sections)

console.log(`[routes] registry patterns extracted: ${sections.modulePatterns.length}`)
console.log(`[routes] app route handlers discovered: ${sections.routeHandlers.length}`)
console.log(
  `[routes] groups: ${sections.backend.length} backend page / ${sections.api.length} API / ${sections.other.length} other`,
)

try {
  fs.mkdirSync(path.dirname(OUTPUT_FILE), { recursive: true })
  fs.writeFileSync(OUTPUT_FILE, manifest)
} catch (error) {
  fail(`cannot write ${path.relative(root, OUTPUT_FILE)}: ${error instanceof Error ? error.message : String(error)}`)
}

const written = fs.readFileSync(OUTPUT_FILE, 'utf8')
if (written !== manifest) fail('generated file does not match the rendered manifest')

const writtenBackend = sectionRows(written, BACKEND_HEADING)
const writtenApi = sectionRows(written, API_HEADING)
const writtenOther = sectionRows(written, OTHER_HEADING)
const writtenTotal = writtenBackend + writtenApi + writtenOther

console.log(
  `[routes] patterns in ${path.relative(root, OUTPUT_FILE)}: ${writtenTotal} (${writtenBackend} backend page + ${writtenApi} API + ${writtenOther} other)`,
)
console.log(
  `[routes] backend pattern count: extracted ${sections.backend.length} == manifest ${writtenBackend}`,
)

if (sections.backend.length !== writtenBackend) fail('backend pattern count drift')
if (sections.backend.length !== headingCount(written, BACKEND_HEADING)) fail('backend heading count drift')
if (sections.api.length !== writtenApi) fail('API route count drift')
if (sections.other.length !== writtenOther) fail('other route count drift')
if (total !== writtenTotal) fail(`total route count drift: expected ${total}, manifest ${writtenTotal}`)

console.log('[routes] OK: backend pattern counts match; manifest is up to date')
